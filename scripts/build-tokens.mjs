// Generates styles/tokens.css from tokens.json (DTCG).
// Usage: node scripts/build-tokens.mjs   (or: npm run tokens)
// No dependencies. Naming: --ds- + token path in kebab-case.

import { readFile, writeFile } from "node:fs/promises";

const root = new URL("..", import.meta.url);
const tokens = JSON.parse(await readFile(new URL("tokens.json", root), "utf8"));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const varName = (path) => `--ds-${path.map(kebab).join("-")}`;

const isToken = (node) => node && typeof node === "object" && "$value" in node;

// Collect every token by dotted path.
const all = new Map();
(function walk(node, path) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (isToken(child)) all.set([...path, key].join("."), child);
    else if (child && typeof child === "object") walk(child, [...path, key]);
  }
})(tokens, []);

const refPattern = /^\{([^}]+)\}$/;

// Resolve a value to CSS. References become var() so the cascade stays live.
function toCss(value, type) {
  if (typeof value === "string") {
    const ref = value.match(refPattern);
    if (ref) {
      if (!all.has(ref[1])) throw new Error(`Unknown reference ${value}`);
      return `var(${varName(ref[1].split("."))})`;
    }
    return value;
  }
  if (type === "fontFamily" && Array.isArray(value))
    return value.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ");
  if (type === "cubicBezier") return `cubic-bezier(${value.join(", ")})`;
  if (type === "shadow")
    return value.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${toCss(s.color, "color")}`).join(", ");
  return String(value);
}

// Spring {duration, bounce} → CSS linear() easing + settle duration (mass = 1).
function springToCss({ duration, bounce }, points = 32) {
  const w0 = (2 * Math.PI) / duration;
  const zeta = Math.min(1, 1 - bounce);
  const x = (t) => {
    if (zeta >= 1) return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
    const wd = w0 * Math.sqrt(1 - zeta * zeta);
    return 1 - Math.exp(-zeta * w0 * t) * (Math.cos(wd * t) + ((zeta * w0) / wd) * Math.sin(wd * t));
  };
  let settle = 0;
  for (let t = 0; t < 10; t += 0.001) if (Math.abs(1 - x(t)) > 0.001) settle = t;
  const stops = Array.from({ length: points + 1 }, (_, i) => (i === points ? 1 : +x((settle * i) / points).toFixed(4)));
  return { easing: `linear(${stops.join(", ")})`, duration: `${Math.round(settle * 1000)}ms` };
}

const lines = [];
for (const [path, token] of all) {
  const parts = path.split(".");
  const name = varName(parts);
  const { $type: type, $value: value } = token;

  if (type === "typography") {
    for (const [prop, v] of Object.entries(value)) {
      const suffix = { fontFamily: "family", fontSize: "size", fontWeight: "weight", lineHeight: "line-height", letterSpacing: "tracking" }[prop];
      lines.push(`${name}-${suffix}: ${toCss(v, prop === "fontFamily" ? "fontFamily" : undefined)};`);
    }
  } else if (type === "spring") {
    const { easing, duration } = springToCss(value);
    lines.push(`${name}: ${easing};`, `${name}-duration: ${duration};`);
  } else if (type === "material") {
    lines.push(
      `${name}-blur: ${value.blur};`,
      `${name}-saturate: ${value.saturate};`,
      `${name}-tint: ${toCss(value.tint)};`,
      `${name}-border: ${toCss(value.border)};`,
      `${name}-shadow: ${toCss(value.shadow)};`,
      `${name}-fallback: ${toCss(value.fallback)};`,
    );
  } else {
    lines.push(`${name}: ${toCss(value, type)};`);
  }
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${lines.map((l) => `  ${l}`).join("\n")}
}
`;

await writeFile(new URL("styles/tokens.css", root), css);
console.log(`styles/tokens.css: ${lines.length} variables`);
